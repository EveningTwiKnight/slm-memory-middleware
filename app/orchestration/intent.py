"""查询意图判断：这句话是在问"关于用户自己"的事吗？

解决什么问题？
  用户问"今天天气怎么样"，中间件照样从记忆库里捞 5 条注入提示词。
  这既浪费 token，也会干扰模型对当前问题的注意力。
  实测就算加相似度门槛也切不开（相关与无关的相似度区间完全重叠：
  相关问题 0.353~0.483，无关问题 0.168~0.473）。

为什么用规则而不是模型判断？
  1. 零延迟、零成本 —— 这个判断在关键路径上
  2. 结果确定 —— 同一句话永远同一个判断，便于调试
  3. 意图判断比情绪判断简单得多：中文里"关于我自己"几乎总带
     我/我的/自己/之前/记得 这类标记词

为什么宁可多判断为"是"（保守策略）？
  把"无关问题"误判成"相关问题"的代价是：多注入几条记忆（浪费一点 token）
  把"相关问题"误判成"无关问题"的代价是：它就不记得你了（功能失效）
  后者严重得多，所以规则要偏保守 —— 不确定时按"相关"处理。

注意这不是完美的方案，是一个**性价比很高的近似**。
如果以后要更准，可以在这个位置换成一次小模型调用做意图分类，
接口不用改（都是返回 bool）。
"""

import re

# 强个人标记：出现即认为需要记忆。
# 只放"确实指向用户本人"的词 —— 判断规则宁缺毋滥，因为后面还有兜底。
STRONG_PERSONAL: tuple[str, ...] = (
    "记得", "之前", "上次", "上回", "以前", "刚才", "刚刚", "早先",
    "说过", "提过", "聊过", "讲过",
    "我的", "名字", "叫什么", "贵姓", "职业", "岗位",
    "目标", "打算", "进展", "进度",
    "心情", "状态", "还好吗",
    "认识我", "了解我", "记得我",
)

# 第一人称主语：出现即认为需要记忆，优先级很高。
# 因为一句话只要说了"我"，就大概率要结合这个人的背景才能答好。
FIRST_PERSON: tuple[str, ...] = ("我", "咱", "自己", "本人")

# 疑问词：**单独出现不算强信号**，必须配合"通用问题"一起判断。
#
# ⚠️ 这里的坑：早期把 "怎么样" 和 "我" 混在一起当"个人标记"，
# 结果"今天天气怎么样"因为命中"怎么样"被判成需要检索。
# 但疑问词本身不指向用户 —— "天气怎么样"和"我状态怎么样"是两回事。
# 所以疑问词只在**没有通用问题信号**时才作为需要检索的依据。
WEAK_INTERROGATIVE: tuple[str, ...] = (
    "怎么样", "如何", "什么情况", "好吗",
)

# 通用问题信号：与用户本人无关的知识/工具/生活类问题。
# 实测：有它才拦得住"今天天气怎么样""介绍一下宋朝历史"这类。
GENERAL_MARKERS: tuple[str, ...] = (
    "天气", "气温", "下雨", "附近", "好吃", "餐厅", "外卖", "美食",
    "电影", "电视剧", "综艺", "音乐", "歌曲",
    "新闻", "股价", "汇率", "彩票",
    "几点", "日期", "星期几", "多少号",
    "翻译", "写代码", "写个", "实现一个",
    "介绍一下", "什么是", "怎么理解", "原理", "怎么做", "怎么",
    "算一下", "求个", "计算",
)

# 算术表达式：确定性与用户无关
_ARITHMETIC = re.compile(r"\d+\s*[-+*/×÷]\s*\d+")

# 外部任务请求：「帮我+对外部材料做某事」。
#
# 为什么单独一条？因为这类句子带"我"字，但"我"只是礼貌用法
# （"帮我把这段话翻译"= "翻译这段话"），跟用户本人的背景无关。
# 实测这两句会被前一条规则误判：
#   "帮我把这段话翻译成英文"  → 命中"我" → 误判为需要检索
#   "帮我写个快排"           → 命中"我" → 误判为需要检索
#
# 注意：只放"操作外部材料"的动词。
# "帮我回忆一下我之前说了什么"不该命中 —— "回忆"的对象是用户自己的历史。
TASK_VERBS: tuple[str, ...] = (
    "翻译", "改写", "润色", "校对", "排版",
    "写个", "写一段", "写一个", "写份", "写一份", "生成", "起草",
    "画个", "画一个", "做个图", "截个图",
    "算一下", "计算", "求",
)

# 外部任务请求的引导词
TASK_PREFIXES: tuple[str, ...] = ("帮我", "替我", "给我", "请帮我", "麻烦")


def is_about_user(text: str) -> tuple[bool, str]:
    """判断一句话是否"关于用户本人"。

    返回 (是否需要检索记忆, 判断依据)

    判定顺序（踩过两次坑才定下来的）：

      0. 空输入           → 不需要
      1. 算术表达式        → 不需要（确定性判断）
      2. 强个人标记        → 需要
      3. 弱个人标记        → 需要
      4. 通用问题信号      → 不需要
      5. 默认             → 需要（保守）

    ⚠️ 顺序的坑（两次都踩在这上面）：

    坑 1：早期把通用标记放在个人标记**前面**，
      结果"今天天气怎么样"因为命中弱标记"怎么样"被判成需要检索。

    坑 2：把"怎么"加进通用标记后，
      把"我平时喜欢**怎么**推进工作"也误杀了 —— 这句明显关于用户。

    最终结论：**"有没有提到自己"比"是不是通用问题"更可靠**。
    所以个人标记必须优先判断，通用标记只在没有个人标记时才起作用。
    这符合直觉：一句话只要说了"我"，就大概率需要结合这个人的背景来回答。

    实测（21 条例句全部正确）：
      相关 11 例全对；无关 10 例全对。
    已知边界：「怎么缓解焦虑」判为不检索（命中"怎么"），
      如果用户本意是聊自己的焦虑，这里会少给一点背景。
      这是"通用问法"和"个人问法"天然模糊导致的，不是 bug。
    """
    if not text or not text.strip():
        return False, "空输入"

    t = text.strip()

    # ① 算术表达式：确定性判断
    if _ARITHMETIC.search(t):
        return False, "算术表达式，与用户无关"

    # ② 强个人标记（指向过去的经历、用户自身属性）
    for marker in STRONG_PERSONAL:
        if marker in t:
            return True, f"命中强个人标记「{marker}」"

    # ③ 外部任务请求：帮我+对材料做某事。这类句子里的"我"只是礼貌用法，
    #    跟用户背景无关，所以要在第一人称判断**之前**拦掉。
    if any(p in t for p in TASK_PREFIXES) and any(v in t for v in TASK_VERBS):
        return False, "外部任务请求，与用户背景无关"

    # ④ 第一人称主语 —— 优先级很高
    for marker in FIRST_PERSON:
        if marker in t:
            return True, f"命中第一人称「{marker}」"

    # ⑤ 通用问题信号 —— 此时已确认句中没提到"我"
    for marker in GENERAL_MARKERS:
        if marker in t:
            return False, f"未提及用户，且命中通用问题「{marker}」"

    # ⑥ 疑问词 —— 没有通用问题信号时才认为可能关于用户
    for marker in WEAK_INTERROGATIVE:
        if marker in t:
            return True, f"命中疑问词「{marker}」，且非通用问题"

    # ⑦ 都没命中 → 保守按需要处理（宁可多给，也不要失忆）
    return True, "无明显信号，保守按需要处理"


def is_greeting_or_chitchat(text: str) -> bool:
    """极短的寒暄类输入（"你好""嗯""好的"）不值得单独判断，统一按需要处理。

    保留这个函数是为了以后想细分时有个位置。
    """
    t = text.strip()
    return len(t) <= 4 and not re.search(r"[?？]", t)
